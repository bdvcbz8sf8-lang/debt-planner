import { expect, test } from '@playwright/test'

test('avalanche puts higher APR debt first in payoff order', async ({ page }) => {
  await page.goto('/')
  await page.getByTestId('add-debt').click()
  await page.getByTestId('add-debt').click()
  const cards = page.locator('.loan-card')
  const first = cards.nth(0)
  const second = cards.nth(1)
  await first.locator('[data-testid^="details-"]').click()
  await second.locator('[data-testid^="details-"]').click()

  await first.locator('.name-input').fill('Debt A')
  await second.locator('.name-input').fill('Debt B')
  await first.locator('label:has-text("Остаток") input').fill('500000')
  await second.locator('label:has-text("Остаток") input').fill('100000')
  await first.locator('label:has-text("%") input').fill('10')
  await second.locator('label:has-text("%") input').fill('30')
  await first.locator('label:has-text("Срок (месяцы)") input').fill('60')
  await second.locator('label:has-text("Срок (месяцы)") input').fill('60')
  await first.locator('label:has-text("Платёж") input').fill('15000')
  await second.locator('label:has-text("Платёж") input').fill('5000')
  await first.locator('label:has-text("Дата платежа") input').fill('2026-02-10')
  await second.locator('label:has-text("Дата платежа") input').fill('2026-02-10')
  await page.getByTestId('strategy-select').selectOption('avalanche')
  await page.getByTestId('calculate-plan').click()
  await expect(page.locator('.errors')).toHaveCount(0)

  await expect(page.getByTestId('payoff-order').locator('li').first()).toContainText('Debt B')
})

